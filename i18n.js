  function detectDefaultLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && TRANSLATIONS[saved]) return saved;
    } catch (_) {}
    const nav = String((navigator.language || "en")).toLowerCase().slice(0, 2);
    if (TRANSLATIONS[nav]) return nav;
    return "en";
  }

  let currentLang = detectDefaultLang();

  function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return currentLang;
    currentLang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (_) {}
    applyDom();
    return currentLang;
  }

  function getLanguage() {
    return currentLang;
  }

  function t(key, vars) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key);
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return str;
  }

  function applyDom(root = document) {
    const els = root.querySelectorAll("[data-i18n]");
    for (const el of els) {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key);
    }
    const phs = root.querySelectorAll("[data-i18n-placeholder]");
    for (const el of phs) {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key));
    }
    const titles = root.querySelectorAll("[data-i18n-title]");
    for (const el of titles) {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.setAttribute("title", t(key));
    }
    document.documentElement.lang = currentLang;
  }

  global.MochiI18n = {
    LANGUAGES,
    getLanguage,
    setLanguage,
    t,
    applyDom
  };
